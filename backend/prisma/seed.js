export async function seedSpaces() {
  for (const space of REQUIRED_SPACES) {
    await prisma.communitySpace.upsert({
      where: { id: space.id },
      update: {
        type: space.type,
        title: space.title,
        category: space.category ?? null,
        icon: space.icon ?? null,
        iconBg: space.iconBg ?? null,
        description: space.description,
        ageGroup: space.ageGroup,
        allowedGendersJson: JSON.stringify(space.allowedGenders || []),
        issuesJson: JSON.stringify(space.issues || []),
        interestsJson: JSON.stringify(space.interests || []),
        maxMembers: space.maxMembers ?? null,
        expect: space.expect ?? null,
        dateLabel: space.dateLabel ?? null,
        timeLabel: space.timeLabel ?? null,
        duration: space.duration ?? null,
        availability: space.availability ?? null,
        hasMeetupSpots: Boolean(space.hasMeetupSpots),
      },
      create: {
        id: space.id,
        type: space.type,
        title: space.title,
        category: space.category ?? null,
        icon: space.icon ?? null,
        iconBg: space.iconBg ?? null,
        description: space.description,
        ageGroup: space.ageGroup,
        allowedGendersJson: JSON.stringify(space.allowedGenders || []),
        issuesJson: JSON.stringify(space.issues || []),
        interestsJson: JSON.stringify(space.interests || []),
        maxMembers: space.maxMembers ?? null,
        memberCount: space.memberCount ?? 0,
        activeNow: space.activeNow ?? 0,
        expect: space.expect ?? null,
        dateLabel: space.dateLabel ?? null,
        timeLabel: space.timeLabel ?? null,
        duration: space.duration ?? null,
        availability: space.availability ?? null,
        hasMeetupSpots: Boolean(space.hasMeetupSpots),
      },
    });
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  seedSpaces()
    .then(() => {
      console.log(`Seeded ${REQUIRED_SPACES.length} community spaces.`);
      return prisma.$disconnect();
    })
    .catch((err) => {
      console.error('Seed failed:', err);
      process.exit(1);
    });
}
